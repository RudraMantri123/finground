def build_dashboard(directory: Path | None = None, results_csv: Path | None = None) -> str:
    """Return the full HTML report as a string."""
    traces = load_traces(directory or trace_dir())
    results = _load_results(results_csv or CONFIG.paths.results / "results.csv")
    width, bucket_label = _bucket_key(traces) if traces else (10, "day (UTC)")

    overall = _summarise(traces) if traces else None
    by_bucket: dict[str, list[dict]] = defaultdict(list)
    by_variant: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for t in traces:
        by_bucket[str(t.get("ts", ""))[:width]].append(t)
        by_variant[(str(t.get("model") or "—"), str(t.get("prompt_version") or "—"))].append(t)
    series = _span_series(traces, width)

    out: list[str] = [_HEAD]
    out.append(
        f'<header><h1>FinGround observability</h1><p class="muted">{len(traces)} traces from '
        f"<code>{_e(directory or trace_dir())}</code> · results from <code>results/results.csv</code>."
        " Rebuild with <code>make dashboard</code> or open <code>/dashboard</code> on the API.</p></header>"
    )

    if overall:
        tiles = [
            ("Traces", str(overall["n"])),
            ("Error rate", _pct(overall["error_rate"])),
            ("Refusal rate", _pct(overall["refusal_rate"])),
            ("Citation coverage", _pct(overall["coverage"])),
            ("Latency p50 / p95", f"{_ms(overall['p50_ms'])} / {_ms(overall['p95_ms'])}"),
            ("Total cost", _usd(overall["cost"])),
        ]
        out.append('<section class="tiles">')
        for label, value in tiles:
            out.append(
                f'<div class="tile"><div class="muted">{label}</div><b>{_e(value)}</b></div>'
            )
        out.append("</section>")
    else:
        out.append(
            '<p class="empty">No traces yet. Hit <code>POST /query</code> or run '
            "<code>scripts/run_benchmark.py</code>; traces land in <code>traces/</code>.</p>"
        )

    if traces:
        out.append(
            f"<section><h2>Over time, by {bucket_label}</h2>"
            '<p class="muted">Scan down a column for the period where a rate jumps, then '
            "filter the trace list below to that period.</p>"
            '<div class="scroll"><table><thead><tr><th>Period</th><th>n</th><th>Errors</th>'
            "<th>Refusals</th><th>Cite coverage</th><th>Judge unsupported</th><th>Cache hits</th>"
            "<th>p50</th><th>p95</th><th>Cost</th><th>Models</th><th>Prompt versions</th>"
            "</tr></thead><tbody>"
        )
        for b in sorted(by_bucket):
            s = _summarise(by_bucket[b])
            out.append(
                f'<tr><td><a href="#" class="period" data-period="{_e(b)}">{_e(b)}</a></td>'
                f"<td>{s['n']}</td><td>{_pct(s['error_rate'])}</td>"
                f"<td>{_pct(s['refusal_rate'])}</td><td>{_pct(s['coverage'])}</td>"
                f"<td>{_pct(s['unsupported'])}</td><td>{_pct(s['cache_hit'])}</td>"
                f"<td>{_ms(s['p50_ms'])}</td><td>{_ms(s['p95_ms'])}</td><td>{_usd(s['cost'])}</td>"
                f"<td>{_e(', '.join(s['models']))}</td><td>{_e(', '.join(s['prompts']) or '—')}</td></tr>"
            )
        out.append("</tbody></table></div></section>")

        out.append(
            "<section><h2>Span latency over time</h2>"
            '<p class="legend"><span class="key s1"></span>p50 <span class="key s2"></span>p95'
            ' <span class="muted">· hover a point for values</span></p><div class="multiples">'
        )
        order = ["(total)", "retrieve", "retrieve.bm25", "retrieve.dense", "retrieve.fusion"]
        order += ["retrieve.company_filter", "retrieve.rerank", "evidence_gate", "generate"]
        names = [n for n in order if n in series] + sorted(n for n in series if n not in order)
        for name in names:
            out.append(
                f"<figure><figcaption>{_e(name)}</figcaption>{_sparkline(name, series[name])}</figure>"
            )
        out.append("</div></section>")

        out.append(
            '<section><h2>By model × prompt version</h2><div class="scroll"><table><thead><tr>'
            "<th>Model</th><th>Prompt version</th><th>n</th><th>Errors</th><th>Refusals</th>"
            "<th>Cite coverage</th><th>Judge unsupported</th><th>p50</th><th>p95</th><th>Cost</th>"
            "</tr></thead><tbody>"
        )
        for (model, pv), group in sorted(by_variant.items()):
            s = _summarise(group)
            out.append(
                f"<tr><td>{_e(model)}</td><td>{_e(pv)}</td><td>{s['n']}</td>"
                f"<td>{_pct(s['error_rate'])}</td><td>{_pct(s['refusal_rate'])}</td>"
                f"<td>{_pct(s['coverage'])}</td><td>{_pct(s['unsupported'])}</td>"
                f"<td>{_ms(s['p50_ms'])}</td><td>{_ms(s['p95_ms'])}</td><td>{_usd(s['cost'])}</td></tr>"
            )
        out.append("</tbody></table></div></section>")

    if results:
        out.append(
            '<section><h2>Leaderboard</h2><p class="muted">Brackets: bootstrap 95% CI. '
            'Latency is LLM generation time.</p><div class="scroll"><table><thead><tr>'
            "<th>Model</th><th>Correctness</th><th>Citation acc</th><th>Hallucination</th>"
            "<th>Refusal cal</th><th>Cite coverage</th><th>Failure</th><th>p50 (s)</th>"
            "<th>p95 (s)</th><th>$/request</th><th>n</th><th>Judge</th></tr></thead><tbody>"
        )
        for r in results:
            out.append(
                f"<tr><td>{_e(r.get('model'))}</td>"
                + _ci_cell(r, "correctness")
                + _ci_cell(r, "citation_accuracy")
                + _ci_cell(r, "hallucination_rate")
                + _ci_cell(r, "refusal_calibration")
                + "".join(
                    f"<td>{_e(r.get(c) or '—')}</td>"
                    for c in (
                        "citation_coverage",
                        "failure_rate",
                        "latency_p50_s",
                        "latency_p95_s",
                        "cost_per_request",
                        "n_questions",
                        "judge",
                    )
                )
                + "</tr>"
            )
        out.append("</tbody></table></div></section>")

    if traces:
        newest = [_drilldown_record(t) for t in traces[-DRILLDOWN_LIMIT:]][::-1]
        payload = json.dumps(newest, ensure_ascii=False, default=str).replace("</", "<\\/")
        out.append(
            "<section><h2>Traces</h2>"
            f'<p class="muted">Newest {len(newest)} traces. Click a row for its spans, '
            "retrieval, rerank movement and answer.</p>"
            '<div class="filters"><input id="q" type="search" placeholder="Filter: text, '
            'model, trace id, period (e.g. 2026-11-17)…" aria-label="Filter traces">'
            '<label><input id="only-bad" type="checkbox"> errors / refusals / uncovered only</label>'
            '<span id="count" class="muted"></span></div>'
            '<div class="scroll"><table id="traces"><thead><tr><th>Time (UTC)</th><th>Source</th>'
            "<th>Model</th><th>Question</th><th>Status</th><th>Total</th><th>Cost</th></tr></thead>"
            '<tbody></tbody></table></div><div id="detail"></div></section>'
            f'<script id="trace-data" type="application/json">{payload}</script>' + _SCRIPT
        )

    out.append("</main></body></html>")
    return "\n".join(out)


def write_dashboard(out_path: Path | None = None, **kwargs: Any) -> Path:
    out_path = out_path or trace_dir() / "dashboard.html"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(build_dashboard(**kwargs), encoding="utf-8")
    return out_path


