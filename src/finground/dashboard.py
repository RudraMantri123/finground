def _e(x: Any) -> str:
    return html.escape("" if x is None else str(x))


def _pct(x: float | None) -> str:
    return "—" if x is None else f"{x:.0%}"


def _ms(x: float | None) -> str:
    if x is None:
        return "—"
    return f"{x / 1000:.2f} s" if x >= 1000 else f"{x:.0f} ms" if x >= 10 else f"{x:.2f} ms"


def _usd(x: float | None) -> str:
    return "—" if x is None else f"${x:.4f}"


def _sparkline(name: str, rows: list[tuple[str, float, float, int]]) -> str:
    """Small-multiple line chart: p50 and p95 for one span over time."""
    w, h, pad_l, pad_b, pad_t = 300, 120, 44, 18, 8
    if not rows:
        return ""
    ymax = max(r[2] for r in rows) or 1.0
    n = len(rows)

    def x(i: int) -> float:
        return pad_l + (w - pad_l - 8) * (i / (n - 1) if n > 1 else 0.5)

    def y(v: float) -> float:
        return pad_t + (h - pad_t - pad_b) * (1 - v / ymax)

    parts = [
        f'<svg viewBox="0 0 {w} {h}" role="img" aria-label="{_e(name)} latency p50 and p95">',
        f'<line class="grid" x1="{pad_l}" x2="{w - 8}" y1="{y(ymax):.1f}" y2="{y(ymax):.1f}"/>',
        f'<line class="axis" x1="{pad_l}" x2="{w - 8}" y1="{y(0):.1f}" y2="{y(0):.1f}"/>',
        f'<text class="tick" x="{pad_l - 4}" y="{y(ymax) + 4:.1f}" text-anchor="end">{_ms(ymax)}</text>',
        f'<text class="tick" x="{pad_l - 4}" y="{y(0) + 4:.1f}" text-anchor="end">0</text>',
        f'<text class="tick" x="{pad_l}" y="{h - 4}">{_e(rows[0][0])}</text>',
    ]
    if n > 1:
        parts.append(
            f'<text class="tick" x="{w - 8}" y="{h - 4}" text-anchor="end">{_e(rows[-1][0])}</text>'
        )
    for idx, cls in ((1, "s1"), (2, "s2")):
        pts = " ".join(f"{x(i):.1f},{y(float(r[idx])):.1f}" for i, r in enumerate(rows))
        if n > 1:
            parts.append(f'<polyline class="line {cls}" points="{pts}"/>')
    for i, r in enumerate(rows):
        tip = f"{r[0]} · p50 {_ms(r[1])} · p95 {_ms(r[2])} · n={r[3]}"
        for idx, cls in ((1, "s1"), (2, "s2")):
            parts.append(
                f'<circle class="dot {cls}" cx="{x(i):.1f}" cy="{y(float(r[idx])):.1f}" r="4">'
                f"<title>{_e(tip)}</title></circle>"
            )
    parts.append("</svg>")
    return "".join(parts)


def _load_results(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with open(path, encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _ci_cell(r: dict, col: str) -> str:
    v = r.get(col) or "—"
    lo, hi = r.get(f"{col}_ci_lo"), r.get(f"{col}_ci_hi")
    ci = f' <span class="muted">[{_e(lo)}, {_e(hi)}]</span>' if lo and hi else ""
    return f"<td>{_e(v)}{ci}</td>"


def _drilldown_record(t: dict) -> dict:
    keep = (
        "trace_id",
        "name",
        "ts",
        "duration_ms",
        "source",
        "run_id",
        "item_id",
        "question",
        "model",
        "prompt_version",
        "prompt_hash",
        "answer",
        "refused",
        "gate",
        "best_dense_sim",
        "citations",
        "citation_coverage",
        "prompt_tokens",
        "completion_tokens",
        "cost_usd",
        "cache_hit",
        "llm_latency_s",
        "error",
        "spans",
        "retrieved",
        "rerank_before",
        "rerank_after",
        "judge_correct",
        "judge_unsupported",
        "judge_error",
    )
    return {k: t[k] for k in keep if k in t}


