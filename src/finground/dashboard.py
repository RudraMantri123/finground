"""Static observability report over ``traces/`` and ``results/results.csv``.

The question this page answers: *quality moved — when, and in which stage?*
It is one self-contained HTML file (inline SVG + a little vanilla JS, no CDN,
no extra dependencies), so it can be generated by a script, served by the API
at ``/dashboard``, attached to an incident, or opened from disk.

Sections, top to bottom:

* headline tiles over all traces (volume, error / refusal rates, latency, cost);
* a per-period table (day, or hour when all traces fall in one day) of error,
  refusal, citation-coverage and judge-unsupported rates, latency and cost,
  plus the models / prompt versions seen — the place to spot "last Tuesday";
* per-span latency p50/p95 over time as small multiples (which stage slowed);
* a model × prompt-version breakdown (did a deploy change behaviour?);
* the leaderboard with bootstrap CIs;
* a filterable trace list with drill-down: span waterfall, retrieved chunks
  and scores, rerank movement, the answer, and any error.
"""

from __future__ import annotations

import csv
import html
import json
from collections import defaultdict
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from .config import CONFIG
from .eval.metrics import percentile
from .tracing import load_traces, trace_dir

DRILLDOWN_LIMIT = 500  # newest traces embedded for drill-down (keeps the page small)


def _rate(flags: Iterable[bool | None]) -> float | None:
    vals = [bool(f) for f in flags if f is not None]
    return sum(vals) / len(vals) if vals else None


def _bucket_key(traces: list[dict]) -> tuple[int, str]:
    """Bucket by day, or by hour when everything happened on one day."""
    days = {str(t.get("ts", ""))[:10] for t in traces}
    return (13, "hour (UTC)") if len(days) <= 1 else (10, "day (UTC)")


def _summarise(group: list[dict]) -> dict[str, Any]:
    durations = [float(t.get("duration_ms") or 0) for t in group]
    costs = [t.get("cost_usd") for t in group if t.get("cost_usd") is not None]
    return {
        "n": len(group),
        "error_rate": _rate(t.get("error") is not None for t in group),
        "refusal_rate": _rate(t.get("refused") for t in group if "refused" in t),
        "coverage": _rate(t.get("citation_coverage") for t in group),
        "unsupported": _rate(t.get("judge_unsupported") for t in group),
        "cache_hit": _rate(t.get("cache_hit") for t in group if "cache_hit" in t),
        "p50_ms": percentile(durations, 50),
        "p95_ms": percentile(durations, 95),
        "cost": sum(costs) if costs else None,
        "models": sorted({str(t.get("model")) for t in group if t.get("model")}),
        "prompts": sorted({str(t.get("prompt_version")) for t in group if t.get("prompt_version")}),
    }


def _span_series(traces: list[dict], width: int) -> dict[str, list[tuple[str, float, float, int]]]:
    """{span name: [(bucket, p50_ms, p95_ms, n), ...]} in bucket order."""
    acc: dict[str, dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    for t in traces:
        b = str(t.get("ts", ""))[:width]
        acc["(total)"][b].append(float(t.get("duration_ms") or 0))
        for s in t.get("spans", []):
            acc[s.get("name", "?")][b].append(float(s.get("duration_ms") or 0))
    out: dict[str, list[tuple[str, float, float, int]]] = {}
    for name, by_bucket in acc.items():
        rows = []
        for b in sorted(by_bucket):
            xs = by_bucket[b]
            p50, p95 = percentile(xs, 50), percentile(xs, 95)
            if p50 is not None and p95 is not None:
                rows.append((b, p50, p95, len(xs)))
        out[name] = rows
    return out


